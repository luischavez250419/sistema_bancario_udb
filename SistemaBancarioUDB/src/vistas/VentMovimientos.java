    private void configurarTabla() {
        // Evita que el usuario edite las celdas directamente en la tabla
        tblmovimientos.setDefaultEditor(Object.class, null);
        tblmovimientos.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
    }

    private void cargarMovimientosEnTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tblmovimientos.getModel();
        modelo.setRowCount(0); // Limpia filas vacías o anteriores
    }

    private void limpiarCampos() {
        txtcodeopera.setText("");
        txttipodeopera.setText("");
        txtnumerocuenta.setText("");
        txtpropietario.setText("");
        txtoperacion.setText("");
        txtfecha.setText("");
        tblmovimientos.clearSelection();
        txtcodeopera.requestFocus();
    }

    private void rellenarFormularioDesdeFila(int fila) {
        if (fila < 0) {
            return;
        }
        DefaultTableModel modelo = (DefaultTableModel) tblmovimientos.getModel();
        txtcodeopera.setText(valorSeguro(modelo.getValueAt(fila, 0)));
        txttipodeopera.setText(valorSeguro(modelo.getValueAt(fila, 1)));
        txtnumerocuenta.setText(valorSeguro(modelo.getValueAt(fila, 2)));
        txtpropietario.setText(valorSeguro(modelo.getValueAt(fila, 3)));
        txtoperacion.setText(valorSeguro(modelo.getValueAt(fila, 4)));
        txtfecha.setText(valorSeguro(modelo.getValueAt(fila, 5)));
    }

    private String valorSeguro(Object valor) {
        return valor != null ? valor.toString() : "";
    }

    private void buscarMovimientoPorCodigo() {
        String codigoBuscado = txtcodeopera.getText().trim();

        if (codigoBuscado.isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "Ingresa el código de la operación para buscar.",
                "Campo obligatorio",
                JOptionPane.WARNING_MESSAGE
            );
            txtcodeopera.requestFocus();
            return;
        }

        // 1. Primero busca si el código ya está cargado en la tabla visible
        DefaultTableModel modelo = (DefaultTableModel) tblmovimientos.getModel();
        for (int i = 0; i < modelo.getRowCount(); i++) {
            String codigoFila = valorSeguro(modelo.getValueAt(i, 0)).trim();
            if (codigoFila.equalsIgnoreCase(codigoBuscado)) {
                tblmovimientos.setRowSelectionInterval(i, i);
                tblmovimientos.scrollRectToVisible(tblmovimientos.getCellRect(i, 0, true));
                rellenarFormularioDesdeFila(i);
                return;
            }
        }

        JOptionPane.showMessageDialog(
            this,
            "No se encontró ningún movimiento con el código: " + codigoBuscado,
            "Sin resultados",
            JOptionPane.INFORMATION_MESSAGE
        );
    }

    private void configurarSeleccionTabla() {
        tblmovimientos.addMouseListener(new MouseAdapter() {
            @Override
            public void mouseClicked(MouseEvent e) {
                int filaSeleccionada = tblmovimientos.getSelectedRow();
                if (filaSeleccionada != -1) {
                    rellenarFormularioDesdeFila(filaSeleccionada);
                }
            }
        });
    }
