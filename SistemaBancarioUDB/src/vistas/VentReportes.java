    private void configurarTabla() {
        // Evita editar celdas directamente en la tabla
        tblGestionreportes.setDefaultEditor(Object.class, null);
        tblGestionreportes.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
    }

    private void actualizarEstadoFiltroCuenta() {
        String seleccionado = (String) cmbreportes.getSelectedItem();
        boolean requiereCuenta = "Transacciones por cuenta".equalsIgnoreCase(seleccionado);
        txtnumero.setEnabled(requiereCuenta);
        lblnmrdecuenta.setEnabled(requiereCuenta);
        if (!requiereCuenta) {
            txtnumero.setText("");
        }
    }

    private void establecerColumnas(String[] columnas) {
        DefaultTableModel modelo = new DefaultTableModel(new Object[][]{}, columnas);
        tblGestionreportes.setModel(modelo);
    }

    private void limpiarReporte() {
        if (cmbreportes.getItemCount() > 0) {
            cmbreportes.setSelectedIndex(0);
        }
        txtnumero.setText("");
        actualizarEstadoFiltroCuenta();

        DefaultTableModel modelo = (DefaultTableModel) tblGestionreportes.getModel();
        modelo.setRowCount(0);

        txtcuentasactivas.setText("0");
        txtsaldoacumulado.setText("0.00");
        txtpromediodesaldo.setText("0.00");
    }

    private void generarReporte() {
        String tipoReporte = (String) cmbreportes.getSelectedItem();
        String numeroCuenta = txtnumero.getText().trim();

        if (tipoReporte == null || tipoReporte.isBlank()) {
            JOptionPane.showMessageDialog(
                this,
                "Selecciona un tipo de reporte.",
                "Reporte requerido",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        if ("Transacciones por cuenta".equalsIgnoreCase(tipoReporte) && numeroCuenta.isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "Ingresa el número de cuenta para consultar Transacciones por cuenta.",
                "Número de cuenta requerido",
                JOptionPane.WARNING_MESSAGE
            );
            txtnumero.requestFocus();
            return;
        }

        // Ajusta las columnas y filas según el reporte seleccionado.
        
        switch (tipoReporte) {
            case "Cuentas activas":
            case "Cuentas bloqueadas":
                establecerColumnas(new String[]{
                    "Nombre del cliente",
                    "Número de cuenta",
                    "Saldo actual",
                    "Estado de cuenta",
                    "Total depositado",
                    "Total retirado",
                    "Último movimiento",
                    "Comentarios"
                });
                
                txtcuentasactivas.setText("0");
                txtsaldoacumulado.setText("0.00");
                txtpromediodesaldo.setText("0.00");
                break;

            case "Clientes Registrados":
            case "Clientes registrados":
                establecerColumnas(new String[]{
                    "Código de cliente",
                    "Nombre del cliente",
                    "Número de cuenta",
                    "Estado de cuenta",
                    "Saldo actual"
                });
                // Ejemplo: llenar filas desde DAO de clientes
                txtcuentasactivas.setText("0");
                txtsaldoacumulado.setText("0.00");
                txtpromediodesaldo.setText("0.00");
                break;

            case "Historial de transacciones":
            case "Transacciones por cuenta":
                establecerColumnas(new String[]{
                    "Código de la operación",
                    "Tipo de operación",
                    "Número de cuenta",
                    "Propietario",
                    "Monto de la operación",
                    "Fecha"
                });
                // Ejemplo: si es "Transacciones por cuenta", filtrar por numeroCuenta
                txtcuentasactivas.setText("0");
                txtsaldoacumulado.setText("0.00");
                txtpromediodesaldo.setText("0.00");
                break;

            case "Total depositado":
            case "Total retirado":
            case "Total transferido":
                establecerColumnas(new String[]{
                    "Código de la operación",
                    "Tipo de operación",
                    "Número de cuenta",
                    "Propietario",
                    "Monto de la operación",
                    "Fecha"
                });
                // Ejemplo: filtrar por tipo de operación y sumar montos
                txtcuentasactivas.setText("0");
                txtsaldoacumulado.setText("0.00");
                txtpromediodesaldo.setText("0.00");
                break;

            default:
                JOptionPane.showMessageDialog(
                    this,
                    "Tipo de reporte no reconocido: " + tipoReporte,
                    "Aviso",
                    JOptionPane.INFORMATION_MESSAGE
                );
                break;
        }
    }
