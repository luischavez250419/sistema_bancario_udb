    private void btnrealizaroperacionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnrealizaroperacionActionPerformed
       
    String numCuenta = txtnumcuenta.getText().trim();
    String tipoOperacion = (String) jboxretirodeposit.getSelectedItem();
    String montoTexto = txtmonto.getText().trim().replace(",", ".");

    // 1. Validar número de cuenta
    if (numCuenta.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "Ingresa el número de cuenta.",
                "Campo obligatorio",
                JOptionPane.WARNING_MESSAGE
        );
        txtnumcuenta.requestFocus();
        return;
    }

    // 2. Validar monto
    if (montoTexto.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "Ingresa el monto de la operación.",
                "Campo obligatorio",
                JOptionPane.WARNING_MESSAGE
        );
        txtmonto.requestFocus();
        return;
    }

    BigDecimal monto;

    try {
        monto = new BigDecimal(montoTexto);
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(
                this,
                "El monto debe ser un número válido (ejemplo: 25.50).",
                "Monto inválido",
                JOptionPane.ERROR_MESSAGE
        );
        txtmonto.requestFocus();
        return;
    }

    // 3. Ejecutar operación mediante el servicio
    try {

        Movimiento movimiento;

        if ("Depósito".equalsIgnoreCase(tipoOperacion)) {

            movimiento = servicio.realizarDeposito(numCuenta, monto);

        } else if ("Retiro".equalsIgnoreCase(tipoOperacion)) {

            movimiento = servicio.realizarRetiro(numCuenta, monto);

        } else {
            return;
        }

        // 4. Mostrar datos generados por SQL
        limpiarCampos();

        txtcodigodeporeti.setText(
                String.valueOf(movimiento.getIdMovimiento())
        );

        txtfechadeposit.setText(
                movimiento.getFechaHora().format(FORMATO_FECHA)
        );

        JOptionPane.showMessageDialog(
                this,
                tipoOperacion + " realizado correctamente.\n"
                + "Código de operación: " + movimiento.getIdMovimiento(),
                "Operación exitosa",
                JOptionPane.INFORMATION_MESSAGE
        );
        
        limpiarCampos();

    } catch (Exception ex) {

        JOptionPane.showMessageDialog(
                this,
                "No se pudo realizar la operación:\n" + ex.getMessage(),
                "Error en la operación",
                JOptionPane.ERROR_MESSAGE
        );
    }
    
    }//GEN-LAST:event_btnrealizaroperacionActionPerformed

