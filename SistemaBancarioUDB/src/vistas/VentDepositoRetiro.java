    private void btnrealizaroperacionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnrealizaroperacionActionPerformed
        String numCuenta = txtnumcuenta.getText().trim();
        String tipoOperacion = (String) jboxretirodeposit.getSelectedItem();
        String montoTexto = txtmonto.getText().trim().replace(",", ".");

        // 1. Validar número de cuenta
        if (numCuenta.isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "Ingresa el número de cuenta.",
                "Campo obligatorio",
                JOptionPane.WARNING_MESSAGE
            );
            txtnumcuenta.requestFocus();
            return;
        }

        // 2. Validar monto
        if (montoTexto.isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "Ingresa el monto de la operación.",
                "Campo obligatorio",
                JOptionPane.WARNING_MESSAGE
            );
            txtmonto.requestFocus();
            return;
        }

        double monto;
        try {
            monto = Double.parseDouble(montoTexto);
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(
                this,
                "El monto debe ser un número válido (por ejemplo: 25.50).",
                "Monto inválido",
                JOptionPane.ERROR_MESSAGE
            );
            txtmonto.requestFocus();
            return;
        }

        if (monto <= 0) {
            JOptionPane.showMessageDialog(
                this,
                "El monto debe ser mayor que cero.",
                "Monto inválido",
                JOptionPane.WARNING_MESSAGE
            );
            txtmonto.requestFocus();
            return;
        }

        // 3. Delegar a la capa de servicio
        try {
            if ("Deposito".equalsIgnoreCase(tipoOperacion)) {
                
                JOptionPane.showMessageDialog(
                    this,
                    "Depósito procesado correctamente para la cuenta " + numCuenta + ".",
                    "Operación exitosa",
                    JOptionPane.INFORMATION_MESSAGE
                );
                limpiarCampos();

            } else if ("Retiro".equalsIgnoreCase(tipoOperacion)) {
                // Aquí llamas al método de tu servicio o DAO para retiro.
                // Ejemplo:
                // Movimiento mov = movimientoServicio.registrarRetiro(numCuenta, monto, descripcion);
                // txtcodigodeporeti.setText(String.valueOf(mov.getIdMovimiento()));
                // txtfechadeposit.setText(String.valueOf(mov.getFecha()));

                JOptionPane.showMessageDialog(
                    this,
                    "Retiro procesado correctamente para la cuenta " + numCuenta + ".",
                    "Operación exitosa",
                    JOptionPane.INFORMATION_MESSAGE
                );
                limpiarCampos();
            }
        } catch (HeadlessException ex) {
            // Si el servicio o DAO lanza una excepción de negocio o SQL (ej. saldo insuficiente o cuenta inexistente)
            JOptionPane.showMessageDialog(
                this,
                "No se pudo realizar la operación: " + ex.getMessage(),
                "Error en la operación",
                JOptionPane.ERROR_MESSAGE
            );
        }
    
    }//GEN-LAST:event_btnrealizaroperacionActionPerformed

