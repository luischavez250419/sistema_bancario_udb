    private void prepararCamposSistema() {
        txtfecha.setText("");
        txtcodigo.setText("");
    }

    private void limpiarCampos() {
        cmbtipodetransfer.setSelectedIndex(0);
        txtcuentaorigen.setText("");
        txtnombrepropiertario.setText("");
        txtcuentadestino.setText("");
        txtnombrepropiertario2.setText("");
        txtmontotransfer.setText("");
        txtdescripcion.setText("");
        prepararCamposSistema();
        txtcuentaorigen.requestFocus();
    }

    private void buscarPropietarioOrigen() {

    String cuentaOrigen = txtcuentaorigen.getText().trim();

    if (cuentaOrigen.isEmpty()) {
        txtnombrepropiertario.setText("");
        return;
    }

    try {

        String nombre = servicio.obtenerNombrePropietario(cuentaOrigen);

        if (nombre == null) {
            txtnombrepropiertario.setText("Cuenta no encontrada");
        } else {
            txtnombrepropiertario.setText(nombre);
        }

    } catch (Exception ex) {

        JOptionPane.showMessageDialog(
                this,
                "Error al consultar el propietario de origen:\n"
                + ex.getMessage(),
                "Error de consulta",
                JOptionPane.ERROR_MESSAGE
        );
    }
}

    private void buscarPropietarioDestino() {

    String cuentaDestino = txtcuentadestino.getText().trim();

    if (cuentaDestino.isEmpty()) {
        txtnombrepropiertario2.setText("");
        return;
    }

    try {

        String nombre = servicio.obtenerNombrePropietario(cuentaDestino);

        if (nombre == null) {
            txtnombrepropiertario2.setText("Cuenta no encontrada");
        } else {
            txtnombrepropiertario2.setText(nombre);
        }

    } catch (Exception ex) {

        JOptionPane.showMessageDialog(
                this,
                "Error al consultar el propietario de destino:\n"
                + ex.getMessage(),
                "Error de consulta",
                JOptionPane.ERROR_MESSAGE
        );
    }
}

    private void configurarAutocompletadoPropietarios() {
        txtcuentaorigen.addFocusListener(new FocusAdapter() {
            @Override
            public void focusLost(FocusEvent e) {
                buscarPropietarioOrigen();
            }
        });

        txtcuentadestino.addFocusListener(new FocusAdapter() {
            @Override
            public void focusLost(FocusEvent e) {
                buscarPropietarioDestino();
            }
        });
    }
