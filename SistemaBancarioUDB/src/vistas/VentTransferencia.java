    private void btnrealizatransferActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnrealizatransferActionPerformed
        String tipoTransferencia = (String) cmbtipodetransfer.getSelectedItem();
        String cuentaOrigen = txtcuentaorigen.getText().trim();
        String cuentaDestino = txtcuentadestino.getText().trim();
        String montoTexto = txtmontotransfer.getText().trim().replace(",", ".");
        String descripcion = txtdescripcion.getText().trim();

        // Actualizar nombres de propietarios por si no salió del campo antes de hacer clic
        buscarPropietarioOrigen();
        buscarPropietarioDestino();

        // 1. Validar cuentas
        if (cuentaOrigen.isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "Ingresa el número de cuenta de origen.",
                "Campo obligatorio",
                JOptionPane.WARNING_MESSAGE
            );
            txtcuentaorigen.requestFocus();
            return;
        }

        if (cuentaDestino.isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "Ingresa el número de cuenta de destino.",
                "Campo obligatorio",
                JOptionPane.WARNING_MESSAGE
            );
            txtcuentadestino.requestFocus();
            return;
        }

        if (cuentaOrigen.equalsIgnoreCase(cuentaDestino)) {
            JOptionPane.showMessageDialog(
                this,
                "La cuenta de origen y la cuenta de destino no pueden ser la misma.",
                "Cuenta inválida",
                JOptionPane.WARNING_MESSAGE
            );
            txtcuentadestino.requestFocus();
            return;
        }

        // 2. Validar monto
        if (montoTexto.isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "Ingresa el monto de la operación.",
                "Campo obligatorio",
                JOptionPane.WARNING_MESSAGE
            );
            txtmontotransfer.requestFocus();
            return;
        }

        double monto;
        try {
            monto = Double.parseDouble(montoTexto);
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(
                this,
                "El monto debe ser un número válido (ejemplo: 100.00).",
                "Monto inválido",
                JOptionPane.ERROR_MESSAGE
            );
            txtmontotransfer.requestFocus();
            return;
        }

        if (monto <= 0) {
            JOptionPane.showMessageDialog(
                this,
                "El monto debe ser mayor que cero.",
                "Monto inválido",
                JOptionPane.WARNING_MESSAGE
            );
            txtmontotransfer.requestFocus();
            return;
        }

        try {
            
            JOptionPane.showMessageDialog(
                this,
                "Transferencia (" + tipoTransferencia + ") validada y lista para registrar.\n"
                + "Origen: " + cuentaOrigen + "\n"
                + "Destino: " + cuentaDestino + "\n"
                + "Monto: " + monto,
                "Transferencia",
                JOptionPane.INFORMATION_MESSAGE
            );
            limpiarCampos();

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(
                this,
                "No se pudo realizar la transferencia: " + ex.getMessage(),
                "Error en la transferencia",
                JOptionPane.ERROR_MESSAGE
            );
        }
    
    }//GEN-LAST:event_btnrealizatransferActionPerformed

